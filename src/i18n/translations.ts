/**
 * UI translations.
 *
 * The interface was English-only with the strings inlined at each call site
 * (TODO section 8), so a French viewer got a French catalogue behind an English
 * UI. Keys are grouped by the screen or concept that owns them, and every key
 * exists in every locale — a missing key falls back to English rather than
 * rendering the raw key, because a stray `settings.downloads` on screen is
 * worse than an English word.
 *
 * Scope is deliberately the user-facing chrome. Title metadata is localized by
 * TMDB via the `language` parameter, not here.
 */
